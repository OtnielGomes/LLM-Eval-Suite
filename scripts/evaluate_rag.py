"""
scripts/evaluate_rag.py
Entry point CLI: uv run evaluate-rag

Use:
uv run evaluate-rag
uv run evaluate-rag --limit 5
uv run evaluate-rag --strategy naive --limit 3
uv run evaluate-rag --strategy naive --model qwen3-coder:480b-cloud --limit 10
uv run evaluate-rag --dataset src/llm_eval/datasets/curated_qa.jsonl

LLM evaluator: Ollama Cloud via langchain-openai (without Google API/ADC)
Embeddings: Ollama local nomic-embed-text (without OPENAI_API_KEY)

WARNING: use curated_qa.jsonl generated by build_datasets.py (do NOT pass --skip-rag-qa).
         This dataset has schema {question, ground_truth} with discursive answers.
         Do NOT use mmlu_sample.jsonl — its 'answer' field is an MCQ letter, incompatible with RAGAS.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import time
from pathlib import Path
from typing import cast

from dotenv import load_dotenv
load_dotenv()

from datasets import Dataset
from langchain_ollama import OllamaEmbeddings
from langchain_openai import ChatOpenAI
from pydantic import SecretStr
from ragas import evaluate
from ragas.embeddings import LangchainEmbeddingsWrapper
from ragas.llms import LangchainLLMWrapper
from ragas.metrics import (
    answer_relevancy,
    context_precision,
    context_recall,
    faithfulness,
)

from scripts.ingest import get_vectorstore
from src.llm_eval.rag.rag_pipeline import RAGPipeline, StrategyName
from src.llm_eval.shared.config import (
    OLLAMA_BASE_URL,
    OLLAMA_CLOUD_BASE_URL,
    OLLAMA_CLOUD_MODEL,
    OLLAMA_EMBED_MODEL,
)
from src.llm_eval.shared.types import RAGResult

# ── Available strategies ───────────────────────────────────────────────────────

STRATEGIES = ["naive", "hyde", "reranking"]

PROJECT_ROOT    = Path(__file__).parent.parent
DEFAULT_DATASET = PROJECT_ROOT / "src" / "llm_eval" / "datasets" / "curated_qa.jsonl"
RESULTS_DIR     = PROJECT_ROOT / "results" / "rag"

# ── Judge LLM (Ollama Cloud) ──────────────────────────────────────────────────

def _make_ragas_llm(judge_model: str) -> LangchainLLMWrapper:
    """
    Build a RAGAS-compatible LLM wrapper using ChatOpenAI + Ollama Cloud.
    The judge model is always passed explicitly — kept separate from the generation model.
    """
    api_key = os.getenv("OLLAMA_API_KEY")
    if not api_key:
        raise ValueError(
            "OLLAMA_API_KEY not found. Set it in .env:\n"
            " OLLAMA_API_KEY=your-key (https://ollama.com/settings/keys)"
        )
    llm = ChatOpenAI(
        model=judge_model,
        base_url=OLLAMA_CLOUD_BASE_URL,
        api_key=SecretStr(api_key),
        temperature=0,
    )
    return LangchainLLMWrapper(llm)

# ── Embeddings evaluator (Ollama local) ───────────────────────────────────────

def _make_ragas_embeddings() -> LangchainEmbeddingsWrapper:
    return LangchainEmbeddingsWrapper(
        OllamaEmbeddings(
            model=OLLAMA_EMBED_MODEL,   # "nomic-embed-text"
            base_url=OLLAMA_BASE_URL,   # "http://localhost:11434"
        )
    )

# ── Dataset loading ────────────────────────────────────────────────────────────

def load_qa_dataset(path: str | Path, limit: int = 0) -> list[dict]:
    """
    Load curated_qa.jsonl for RAGAS evaluation.

    Expected schema per item (generated by build_datasets.py):
      - question     (str, required)
      - ground_truth (str, discursive answer generated by the LLM from the corpus)

    If 'ground_truth' is absent, falls back to 'answer' provided it contains
    more than 10 words (i.e. a discursive response, not an MCQ letter).
    To regenerate the dataset correctly:
      uv run build-datasets --skip-mmlu --skip-humaneval
    """
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f"Dataset not found: {path}\n"
            "Run: uv run build-datasets --skip-mmlu --skip-humaneval"
        )

    items: list[dict] = []
    with open(path, encoding="utf-8") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                item = json.loads(line)
            except json.JSONDecodeError as e:
                raise ValueError(f"Invalid JSON at line {lineno} of {path}: {e}") from e

            if "question" not in item:
                raise ValueError(f"Item at line {lineno} is missing required field 'question': {item}")

            # Normalise ground_truth — accept 'answer' as fallback if discursive
            if "ground_truth" not in item:
                raw        = item.get("answer", "")
                word_count = len(raw.split())
                if word_count < 10:
                    raise ValueError(
                        f"\n\n❌ Line {lineno}: field 'answer' has only {word_count} word(s) ({raw!r}).\n"
                        f"   curated_qa.jsonl must contain discursive answers generated by the LLM,\n"
                        f"   NOT MCQ letters from MMLU.\n\n"
                        f"   Fix: regenerate the dataset with:\n"
                        f"   uv run build-datasets --skip-mmlu --skip-humaneval\n"
                    )
                item["ground_truth"] = raw

            items.append(item)

    if not items:
        raise ValueError(f"No valid Q&A pairs found in: {path}")

    if limit and limit > 0:
        items = items[:limit]

    print(f" ✅ {len(items)} Q&A pairs loaded from {path.name}")
    return items

# ── Slug helper ───────────────────────────────────────────────────────────────

def _model_slug(model: str) -> str:
    """Convert 'qwen3-coder:480b-cloud' → 'qwen3-coder_480b-cloud'."""
    return re.sub(r"[:/\\]", "_", model)

# ── Strategy execution ─────────────────────────────────────────────────────────

def _run_strategy(
    strategy: str,
    qa_pairs: list[dict],
    gen_model: str,
    judge_model: str,
) -> dict:
    vs = get_vectorstore()
    pipeline = RAGPipeline(
        vectorstore=vs,
        strategy=cast(StrategyName, strategy),
    )

    results: list[dict] = []
    start = time.monotonic()

    print(f"\n{'=' * 60}")
    print(f" RAG Eval: {strategy} | {len(qa_pairs)} answers")
    print(f" Generation model : {gen_model}")
    print(f" Judge model      : {judge_model}")
    print(f"{'=' * 60}")

    for i, qa in enumerate(qa_pairs, start=1):
        t0 = time.monotonic()
        out: RAGResult = pipeline.query(
            question=qa["question"],
            ground_truth=qa["ground_truth"],
        )
        latency_ms = int((time.monotonic() - t0) * 1000)
        print(f" [{i:>3}/{len(qa_pairs)}] latency: {latency_ms}ms | context: {len(out.contexts)}")
        results.append({
            "question":     out.question,
            "answer":       out.answer,
            "contexts":     out.contexts,
            "ground_truth": out.ground_truth,
        })

    elapsed = time.monotonic() - start
    print(f"\n ✅ {len(results)} answers generated in {elapsed:.1f}s")
    print(" Calculating RAGAS metrics...")

    ragas_dataset = Dataset.from_list(results)
    scores = evaluate(
        ragas_dataset,
        metrics=[context_precision, context_recall, faithfulness, answer_relevancy],
        llm=_make_ragas_llm(judge_model),
        embeddings=_make_ragas_embeddings(),
    )

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    gen_slug = _model_slug(gen_model)
    out_file = RESULTS_DIR / f"ragas_{strategy}_{gen_slug}.json"

    scores_dict = (
        scores.to_pandas().to_dict(orient="records")
        if hasattr(scores, "to_pandas") else {}
    )
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(
            {
                "strategy":    strategy,
                "gen_model":   gen_model,
                "judge_model": judge_model,
                "n":           len(qa_pairs),
                "scores":      scores_dict,
            },
            f, indent=2, ensure_ascii=False,
        )
    print(f" ✅ Results saved to '{out_file}'")

    return {"strategy": strategy, "gen_model": gen_model, "scores": scores_dict}

# ── CLI ────────────────────────────────────────────────────────────────────────

def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate RAG strategies with RAGAS.")
    parser.add_argument(
        "--dataset",
        default=str(DEFAULT_DATASET),
        help=(
            "Path to the RAG QA JSONL (default: curated_qa.jsonl). "
            "Must contain {question, ground_truth} with discursive answers. "
            "Do NOT use mmlu_sample.jsonl."
        ),
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=0,
        help="Limit the number of questions evaluated (0 = all).",
    )
    parser.add_argument(
        "--strategy",
        choices=STRATEGIES + ["all"],
        default="all",
        help="RAG strategy to evaluate (default: all).",
    )
    parser.add_argument(
        "--model",
        type=str,
        default=None,
        help=(
            "Generation model override (default: OLLAMA_CLOUD_MODEL from .env). "
            "Example: --model gpt-oss:20b-cloud"
        ),
    )
    parser.add_argument(
        "--judge",
        type=str,
        default=None,
        help=(
            "Judge model for RAGAS evaluation (default: OLLAMA_JUDGE_MODEL from .env, "
            "fallback: qwen3-coder:480b-cloud). Use a large model for stable JSON parsing."
        ),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # Resolution order: CLI flag > .env > config default
    gen_model = (
        args.model
        or os.getenv("OLLAMA_CLOUD_MODEL")
        or OLLAMA_CLOUD_MODEL
    )
    judge_model = (
        args.judge
        or os.getenv("OLLAMA_JUDGE_MODEL")
        or "qwen3-coder:480b-cloud"
    )

    qa_pairs   = load_qa_dataset(args.dataset, limit=args.limit)
    strategies = STRATEGIES if args.strategy == "all" else [args.strategy]

    for strategy in strategies:
        _run_strategy(strategy, qa_pairs, gen_model, judge_model)

    print("\n✅ Evaluation completed. Results in 'results/rag/'")


if __name__ == "__main__":
    main()
